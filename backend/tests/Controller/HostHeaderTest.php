<?php

declare(strict_types=1);

namespace App\Tests\Controller;

use App\Tests\Helper\DatabaseResetter;
use App\Tests\Helper\TestHelper;
use Doctrine\ORM\EntityManagerInterface;
use Symfony\Bundle\FrameworkBundle\KernelBrowser;
use Symfony\Bundle\FrameworkBundle\Test\WebTestCase;
use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\Mime\Email;
use Symfony\Component\PasswordHasher\Hasher\UserPasswordHasherInterface;
use Symfony\Component\Routing\Generator\UrlGeneratorInterface;

/**
 * Audit M2: the Host header must not influence links in mails or redirects, and hosts other than the
 * configured ones (APP_URL / FRONTEND_URL / BACKEND_URL, loopback) are rejected (framework.trusted_hosts).
 */
class HostHeaderTest extends WebTestCase
{
    private static KernelBrowser $client;
    private static EntityManagerInterface $em;
    private static UserPasswordHasherInterface $hasher;

    public static function setUpBeforeClass(): void
    {
        self::$client = static::createClient();
        self::$hasher = static::getContainer()->get(UserPasswordHasherInterface::class);
    }

    protected function setUp(): void
    {
        self::$em = static::getContainer()->get(EntityManagerInterface::class);
        DatabaseResetter::reset(self::$em);
    }

    protected function tearDown(): void
    {
        // Keep the kernel alive across tests (see AuthTest).
    }

    private static function post(string $path, array $body, string $host): void
    {
        self::$client->request('POST', $path, [], [], [
            'CONTENT_TYPE' => 'application/json',
            'HTTP_HOST' => $host,
            'REMOTE_ADDR' => '10.'.random_int(0, 255).'.'.random_int(0, 255).'.'.random_int(1, 254),
        ], (string) json_encode($body));
    }

    public function testForgedHostIsRejectedAndSendsNoMail(): void
    {
        $user = TestHelper::createUser(self::$em, self::$hasher, 'host.'.bin2hex(random_bytes(4)).'@example.com');

        foreach (['attacker.example', 'localhost.attacker.example', 'attacker.example:3001', 'xlocalhost'] as $host) {
            self::post('/api/auth/forgot-password', ['email' => $user->getEmail()], $host);
            $this->assertSame(400, self::$client->getResponse()->getStatusCode(), $host);
            $this->assertEmailCount(0);
        }
    }

    public function testDisallowedHostIsRejectedOnEveryRoute(): void
    {
        self::$client->request('GET', '/api/health', [], [], ['HTTP_HOST' => 'attacker.example']);
        $this->assertSame(400, self::$client->getResponse()->getStatusCode());

        self::$client->request('GET', '/api/health', [], [], ['HTTP_HOST' => 'localhost']);
        $this->assertSame(200, self::$client->getResponse()->getStatusCode());
    }

    public function testMailLinkIgnoresAnAllowedButDifferentHost(): void
    {
        $user = TestHelper::createUser(self::$em, self::$hasher, 'host.'.bin2hex(random_bytes(4)).'@example.com');
        // 127.0.0.1 passes trusted_hosts (loopback), but the link must still point at FRONTEND_URL.
        self::post('/api/auth/forgot-password', ['email' => $user->getEmail()], '127.0.0.1:9999');
        $this->assertSame(204, self::$client->getResponse()->getStatusCode());

        $mail = $this->getMailerMessage();
        $this->assertInstanceOf(Email::class, $mail);
        $html = (string) $mail->getHtmlBody();
        $frontend = rtrim((string) $_ENV['FRONTEND_URL'], '/');
        $this->assertStringContainsString('href="'.$frontend.'/reset-password?token=', $html);
        $this->assertStringNotContainsString('127.0.0.1', $html);
        $this->assertStringNotContainsString('9999', $html);
    }

    public function testRouterGeneratesAbsoluteUrlsFromBackendUrlNotTheHostHeader(): void
    {
        // The OAuth redirect_uri (knpu client bundle) is generated by the router during the request.
        self::$client->request('GET', '/api/health', [], [], ['HTTP_HOST' => '127.0.0.1:9999']);
        $this->assertSame(200, self::$client->getResponse()->getStatusCode());

        $url = static::getContainer()->get('router')->generate('oauth_callback', ['provider' => 'google'], UrlGeneratorInterface::ABSOLUTE_URL);
        $this->assertSame(rtrim((string) $_ENV['BACKEND_URL'], '/').'/api/auth/oauth/google/callback', $url);
    }

    public function testTrustedHostsAreConfiguredFromTheUrls(): void
    {
        $patterns = Request::getTrustedHosts();
        $this->assertNotSame([], $patterns);
        $this->assertSame(1, preg_match($patterns[0], 'localhost'));
        $this->assertSame(0, preg_match($patterns[0], 'attacker.example'));
    }
}
